"""Invoke the server's installed daily report skill with authorized task data."""
import hashlib
import json
import logging
import os
import subprocess
import sys
from pathlib import Path

from fastapi import HTTPException

log = logging.getLogger(__name__)
DEFAULT_SKILL_DIR = Path(__file__).resolve().parents[2] / '.skills' / 'tuitui-daily-report'


def get_skill_dir():
    return Path(os.environ.get('TASK_DAILY_REPORT_SKILL_DIR') or DEFAULT_SKILL_DIR)


def _invoke_skill(payload, mode):
    skill_dir = get_skill_dir()
    script = skill_dir / 'scripts' / 'fetch_daily_report.py'
    try:
        manifest = json.loads((skill_dir / 'platform-install.json').read_text())
        digest = hashlib.sha256(script.read_bytes()).hexdigest()
        if (manifest['script_sha256'] != digest or manifest['platform_adapter_version'] != 2
                or manifest.get('template_sha256') != hashlib.sha256((skill_dir / 'references/template.html').read_bytes()).hexdigest()):
            raise ValueError('skill installation mismatch')
    except (OSError, ValueError, KeyError):
        raise HTTPException(503, detail='日报 skill 未安装或安装不完整，请联系管理员') from None
    data = json.dumps(payload, ensure_ascii=False)
    if len(data.encode('utf-8')) > 2_000_000:
        raise HTTPException(422, detail='所选任务内容过多，请缩小筛选范围后生成日报')
    try:
        result = subprocess.run([sys.executable, str(script), mode], input=data,
            text=True, encoding='utf-8', capture_output=True, timeout=10, cwd=skill_dir,
            env={'PATH': os.defpath, 'PYTHONIOENCODING': 'utf-8', 'PYTHONUTF8': '1'})
        if result.returncode:
            raise ValueError('skill failed')
        output = json.loads(result.stdout)
        keys = ('html',) if mode == '--html-json' else ('title', 'content')
        if any(not isinstance(output.get(k), str) or not output[k].strip() for k in keys):
            raise ValueError('empty skill output')
    except subprocess.TimeoutExpired:
        raise HTTPException(504, detail='日报生成超时，请缩小筛选范围后重试') from None
    except (OSError, ValueError, KeyError, TypeError):
        log.exception('Daily report skill failed; task_count=%s', len(payload.get('tasks', [])))
        raise HTTPException(502, detail='日报 skill 生成失败，请重试或联系管理员') from None
    return output, manifest


def render_task_digest_html(payload):
    output, _ = _invoke_skill(payload, '--html-json')
    if len(output['html'].encode('utf-8')) > 2_000_000:
        raise HTTPException(422, detail='日报 HTML 内容过多，请精简后重试')
    return output['html']


def generate_task_digest(payload):
    output, manifest = _invoke_skill(payload, '--tasks-json')
    title, content = output['title'], output['content']
    if len(title) > 255 or len(content) > 60000:
        raise HTTPException(422, detail='生成的日报超出可保存长度，请缩小筛选范围后重试')
    log.info('Daily report generated by skill=%s adapter=%s tasks=%s',
             manifest['name'], manifest['platform_adapter_version'], len(payload.get('tasks', [])))
    return {'title': title, 'content': content, 'generator': {
        'name': manifest['name'], 'adapter_version': manifest['platform_adapter_version'],
        'archive_sha256': manifest['archive_sha256']}}
