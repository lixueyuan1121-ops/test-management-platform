// Local-only UI regression. Every API response is mocked.
const { chromium } = require('../../tools/qalab-runner/eval/node_modules/playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], writes = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => localStorage.setItem('tp_token', 'mock-local-only'));
    const queries = [1, 2, 3].map(id => ({ id, title: `用例${id}`, prompt: '完整提问内容\n'.repeat(15), expected: '完整预期', turn_index: 0 }));
    const task = { id: 18, name: '回归专项', description: '本地验证', query_ids: [1], status: 'done', target_engines: ['namiwork'], summary_html: '<p>综合评价正文</p>' };
    await page.route(url => url.pathname.startsWith('/api/'), async route => {
      const req = route.request(), path = new URL(req.url()).pathname;
      let data = [];
      if (req.method() !== 'GET') writes.push({ path, body: req.postData() ? req.postDataJSON() : null });
      if (path.endsWith('/auth/me')) data = { user: { id: 1, name: 'Test' }, is_platform_admin: true, memberships: [] };
      if (path.endsWith('/projects')) data = [{ id: 1, name: '测评项目' }];
      if (path.endsWith('/eval-tasks')) data = [task];
      if (path.endsWith('/ai/eval-queries')) data = queries;
      if (path.endsWith('/ai/eval-engines')) data = [{ engine: 'namiwork', label: '纳米Work' }];
      if (path.endsWith('/eval-tasks/18/runs')) data = { task, runs: [] };
      if (path.endsWith('/devices')) data = [{ name: '测试机', runner_id: 'runner-1' }];
      if (path.endsWith('/eval-queue/enqueue')) data = { run_ids: [1], batch_id: 'mock-batch' };
      await route.fulfill({ json: { code: 0, data } });
    });
    const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5189';
    await page.goto(`${base}/eval-tasks`);
    await page.getByRole('button', { name: '回归专项', exact: true }).waitFor();
    await page.getByRole('textbox', { name: '查找功能' }).fill('设备');
    assert(await page.getByRole('menuitem', { name: '设备看板', exact: true }).isVisible());
    await page.getByRole('textbox', { name: '查找功能' }).clear();
    await page.getByRole('textbox', { name: '搜索任务', exact: true }).fill('不存在');
    await page.getByText('没有符合筛选条件的任务').waitFor();
    await page.getByRole('textbox', { name: '搜索任务', exact: true }).clear();
    await page.getByRole('button', { name: '更多操作 回归专项' }).click();
    await page.getByRole('menuitem', { name: '删除任务', exact: true }).click();
    await page.locator('.el-message-box').getByRole('button', { name: '取消', exact: true }).click();
    assert.equal(writes.length, 0);
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    const editor = page.getByRole('dialog', { name: '编辑测评任务' });
    await editor.getByRole('textbox', { name: '搜索用例标题' }).fill('用例2');
    await editor.locator('.el-checkbox').filter({ has: page.getByRole('checkbox', { name: '选择 用例2', exact: true }) }).click();
    await editor.getByRole('textbox', { name: '搜索用例标题' }).clear();
    await editor.getByText('已选 2', { exact: true }).click();
    assert.equal(await editor.locator('.el-table__body-wrapper tbody tr').count(), 2);
    await page.waitForTimeout(350);
    await page.screenshot({ path: '/tmp/eval-task-editor-desktop.png' });
    await editor.getByRole('button', { name: '保存', exact: true }).click();
    await editor.waitFor({ state: 'hidden' });
    assert.deepEqual(writes.find(w => w.path === '/api/eval-tasks/18').body.query_ids, [1, 2]);
    await page.getByRole('button', { name: '回归专项', exact: true }).click();
    await page.getByRole('tab', { name: '综合评价', exact: true }).click();
    await page.getByText('综合评价正文').waitFor();
    await page.goto(`${base}/eval-library`);
    await page.getByRole('button', { name: '用例1', exact: true }).click();
    await page.getByRole('heading', { name: '提问 Prompt' }).waitFor();
    await page.getByRole('button', { name: 'Close this dialog' }).click();
    await page.locator('.el-table__body-wrapper .el-checkbox').first().click();
    await page.getByRole('button', { name: '配置并下发', exact: true }).click();
    const dispatch = page.getByRole('dialog', { name: '下发测评用例' });
    await dispatch.getByRole('textbox', { name: '模型', exact: true }).fill('test-model');
    await dispatch.getByRole('button', { name: '确认下发', exact: true }).click();
    await dispatch.waitFor({ state: 'hidden' });
    const payload = writes.find(w => w.path.endsWith('/enqueue')).body;
    assert.deepEqual(payload.eval_query_ids, [1]);
    assert.equal(payload.runner, 'runner-1');
    assert.equal(payload.target_engine, 'namiwork');
    assert.equal(payload.dialog_options.model, 'test-model');
    await page.screenshot({ path: '/tmp/eval-library-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '展开侧栏', exact: true }).waitFor();
    await page.getByRole('button', { name: '配置并下发', exact: true }).click();
    await page.waitForTimeout(350);
    const box = await dispatch.boundingBox();
    assert(box.x >= 0 && box.x + box.width <= 391);
    await page.screenshot({ path: '/tmp/eval-dispatch-mobile.png' });
    await dispatch.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByRole('button', { name: '删除用例 用例1', exact: true }).click();
    await page.locator('.el-message-box').getByRole('button', { name: '取消', exact: true }).click();
    assert(!writes.some(w => w.path === '/api/ai/eval-queries/1'));
    await page.getByRole('button', { name: '删除用例 用例1', exact: true }).click();
    await page.locator('.el-message-box').getByRole('button', { name: '确认删除', exact: true }).click();
    await page.getByRole('button', { name: '用例1', exact: true }).waitFor({ state: 'hidden' });
    assert.equal(writes.filter(w => w.path === '/api/ai/eval-queries/1').length, 1);
    assert(await page.getByRole('button', { name: '用例2', exact: true }).isVisible());
    assert.deepEqual(errors, []);
    console.log('PASS: navigation, task filters, selection preservation, detail tabs, dispatch payload, mobile dialog');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
