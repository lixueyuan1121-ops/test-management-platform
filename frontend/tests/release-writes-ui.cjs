const { chromium } = require('../../tools/qalab-runner/eval/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], writes = [];
    let failWrite = true, admin = true;
    const row = { id: 11, version: 'v1.0', release_date: '2026-09-10', req_count: 2, sub_product: '纳米Work Android端', channel: ['官网'], content: '原上线内容', memo: '原备忘' };
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => localStorage.setItem('tp_token', 'mock-local-only'));
    await page.route(url => url.pathname.startsWith('/api/'), async route => {
      const req = route.request(), path = new URL(req.url()).pathname;
      let data = [];
      if (path === '/api/auth/me') data = { user: { id: 1, name: '测试员' }, is_platform_admin: admin, memberships: [{ project_id: 1, role: 'member' }] };
      if (path === '/api/projects') data = [{ id: 1, name: '应用项目', platform_type: 'app' }];
      if (path === '/api/releases') data = { items: [row], total: 1 };
      if (path === '/api/releases/stats') data = { total_releases: 1, total_reqs: 2, this_month: 1, latest_date: '2026-09-10', trend: [] };
      if (path === '/api/releases/quality') data = { items: [] };
      if (req.method() !== 'GET') {
        writes.push({ path, method: req.method(), body: req.postData() ? req.postDataJSON() : null });
        if (failWrite) return route.fulfill({ status: 500, json: { msg: '模拟发版保存失败' } });
      }
      await route.fulfill({ json: { code: 0, data } });
    });
    const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5189';
    await page.goto(`${base}/releases`);
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    let dialog = page.locator('.el-dialog');
    await dialog.getByLabel('上线内容', { exact: true }).fill('修改后的上线内容');
    await dialog.getByLabel('备忘', { exact: true }).fill('修改备忘');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await page.getByText('模拟发版保存失败', { exact: true }).waitFor();
    assert(await dialog.isVisible());
    assert.equal(await dialog.getByLabel('上线内容', { exact: true }).inputValue(), '修改后的上线内容');
    failWrite = false;
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.deepEqual(writes.at(-1), { path: '/api/releases/11', method: 'PATCH', body: { version: 'v1.0', release_date: '2026-09-10', req_count: 2, sub_product: '纳米Work Android端', channel: ['官网'], content: '修改后的上线内容', memo: '修改备忘' } });
    await page.getByRole('button', { name: '删除', exact: true }).click();
    await page.locator('.el-message-box').getByRole('button', { name: '取消', exact: true }).click();
    assert.equal(writes.length, 2);
    failWrite = true;
    await page.getByRole('button', { name: '删除', exact: true }).click();
    const deleteFailure = page.waitForResponse(response => response.url().endsWith('/api/releases/11') && response.request().method() === 'DELETE' && response.status() === 500);
    await page.locator('.el-message-box').getByRole('button', { name: '确认删除', exact: true }).click();
    await deleteFailure;
    failWrite = false;
    await page.getByRole('button', { name: '删除', exact: true }).click();
    await page.locator('.el-message-box').getByRole('button', { name: '确认删除', exact: true }).click();
    await page.getByText('已删除', { exact: true }).waitFor();
    assert.deepEqual(writes.at(-1), { path: '/api/releases/11', method: 'DELETE', body: null });
    await page.getByRole('button', { name: '登记发版', exact: true }).click();
    dialog = page.locator('.el-dialog');
    await dialog.getByLabel('版本号', { exact: true }).fill('v2.0');
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(writes.at(-1).path, '/api/releases');
    assert.equal(writes.at(-1).body.project_id, 1);
    assert.equal(writes.at(-1).body.version, 'v2.0');
    admin = false;
    await page.goto(`${base}/releases`);
    await page.getByRole('button', { name: '详情', exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '编辑', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '删除', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '登记发版', exact: true }).count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS release edit failure retention, channel/content payload, create project association, delete cancellation/retry and read-only member controls');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
