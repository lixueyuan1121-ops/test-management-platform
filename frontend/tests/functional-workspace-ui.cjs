const { chromium } = require('../../tools/qalab-runner/eval/node_modules/playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], writes = [], caseQueries = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => localStorage.setItem('tp_token', 'mock-local-only'));
    const plans = Array.from({ length: 50 }, (_, i) => ({ id: i + 1, name: `计划${i + 1}`, runner: 'runner-1', case_count: 3, schedule_enabled: i % 2 === 0 }));
    await page.route(url => url.pathname.startsWith('/api/'), async route => {
      const req = route.request(), url = new URL(req.url()), path = url.pathname;
      let data = [];
      if (req.method() !== 'GET') writes.push({ path, body: req.postDataJSON() });
      if (path.endsWith('/auth/me')) data = { user: { id: 1, name: 'Test' }, is_platform_admin: true, memberships: [] };
      if (path.endsWith('/projects')) data = [{ id: 1, name: '功能测试项目' }];
      if (path.endsWith('/devices')) data = [{ name: '测试机', runner_id: 'runner-1' }];
      if (path.endsWith('/test-plans')) data = plans;
      if (path.endsWith('/tasks')) data = [{ id: 1, description: '登录验证', assigned_to_name: '张三', status: 'pending' }, { id: 2, description: '支付验证', assigned_to_name: '李四', status: 'pending' }];
      if (path.endsWith('/checklist-summary')) data = {};
      if (path.endsWith('/feedback/imports')) data = [{ id: 1, filename: '反馈.md', source_bot: 'bot', status: 'done', file_count: 1, case_count: 2, script_total: 0 }];
      if (path.endsWith('/feedback/defense-calendar')) data = { days: [], streak: 0, total_guard_days: 0 };
      if (path.endsWith('/perf/jobs')) data = { id: 1 };
      if (path.endsWith('/perf/runs/1/prompt')) data = { status: 'running', scenario: '冷启动', variant: '测试版本', runner: 'win-01', prompt: '启动测试应用' };
      if (path.endsWith('/exec-queue/history')) data = [{ id: 1, batch_id: 'batch-pending', status: 'running', title: '运行中的用例', runner: 'runner-1', created_at: '2026-09-10T10:00:00' }];
      if (path.endsWith('/ai/cases')) {
        caseQueries.push(Object.fromEntries(url.searchParams));
        data = { items: Array.from({ length: 50 }, (_, i) => ({ id: i + 1, title: `功能用例${i + 1}`, steps: '完整步骤\n'.repeat(20), expected: '验证完整预期', review_status: 'adopted', exec_kind: 'gui', task_id: 1 })), total: 50 };
      }
      await route.fulfill({ json: { code: 0, data } });
    });
    const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5189';
    await page.goto(`${base}/test-plans`);
    await page.getByRole('textbox', { name: '搜索计划', exact: true }).fill('计划50');
    await page.getByText('共 1 个计划', { exact: true }).waitFor();
    await page.getByRole('textbox', { name: '搜索计划', exact: true }).clear();
    await page.getByRole('button', { name: '新建计划', exact: true }).click();
    const editor = page.getByRole('dialog', { name: '新建测试计划', exact: true });
    await editor.getByPlaceholder('如 每日冒烟回归').fill('新增冒烟');
    await editor.getByRole('button', { name: '保存', exact: true }).click();
    await editor.waitFor({ state: 'hidden' });
    assert.deepEqual(writes[0].body, { project_id: 1, name: '新增冒烟', description: '', runner: 'runner-1' });
    await page.locator('.main').evaluate(node => node.scrollTop = 900);
    await page.waitForTimeout(300);
    const heading = await page.locator('.workspace-toolbar').boundingBox();
    assert(heading.y >= 55 && heading.y < 85);
    await page.screenshot({ path: '/tmp/functional-plans-desktop.png' });
    await page.goto(`${base}/tasks`);
    await page.getByRole('textbox', { name: '搜索任务名称或负责人' }).fill('张三');
    await page.getByText('共 1 个任务', { exact: true }).waitFor();
    assert.equal(await page.locator('.el-table__body-wrapper tbody tr').count(), 1);
    await page.goto(`${base}/case-library`);
    await page.getByText('功能用例1', { exact: true }).waitFor();
    await page.getByPlaceholder('按测试点搜索').fill('登录');
    await page.getByRole('button', { name: '查询', exact: true }).click();
    await page.waitForTimeout(300);
    assert.equal(caseQueries.at(-1).keyword, '登录');
    await page.locator('.el-table__body-wrapper .el-checkbox').first().click();
    await page.locator('.main').evaluate(node => node.scrollTop = 900);
    await page.waitForTimeout(300);
    const dispatch = await page.getByRole('button', { name: '发送到执行机', exact: true }).boundingBox();
    assert(dispatch.y > 55 && dispatch.y < 350);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '收起侧栏' }).click();
    await page.waitForTimeout(350);
    assert.equal(await page.getByPlaceholder('按测试点搜索').isVisible(), false);
    await page.getByRole('button', { name: '筛选', exact: true }).click();
    assert(await page.getByPlaceholder('按测试点搜索').isVisible());
    await page.getByRole('button', { name: '筛选', exact: true }).click();
    const selectedInfo = await page.locator('.sel-info').boundingBox();
    await page.screenshot({ path: '/tmp/functional-cases-mobile.png' });
    assert(selectedInfo.height < 30 && selectedInfo.width > 45, JSON.stringify(selectedInfo));
    const runner = await page.locator('.dispatch-bar .el-select').boundingBox();
    assert(runner.width >= 160 && runner.x + runner.width <= 391);
    await page.screenshot({ path: '/tmp/functional-cases-mobile.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    for (const path of ['/adopted-cases', '/regression-cases']) {
      await page.goto(`${base}${path}`);
      // Scroll the table horizontally to the title while retaining native table interaction.
      const title = page.getByRole('button', { name: '功能用例1', exact: true });
      await title.click();
      await page.getByRole('heading', { name: '步骤', exact: true }).waitFor();
      await page.getByText('验证完整预期', { exact: true }).waitFor();
      const drawer = await page.locator('.el-drawer').boundingBox();
      assert(drawer.width <= 391);
    }
    await page.goto(`${base}/exec-results?project_id=1&batch_id=batch-pending`);
    await page.getByText('尚未全部判定', { exact: true }).waitFor();
    await page.getByText('运行中的用例', { exact: true }).waitFor();
    assert.equal(await page.getByText('全部通过', { exact: true }).count(), 0);
    await page.screenshot({ path: '/tmp/functional-exec-mobile.png' });
    await page.goto(`${base}/feedback-imports`);
    await page.getByRole('button', { name: '筛选', exact: true }).click();
    await page.getByRole('textbox', { name: '搜索导入记录' }).fill('不存在');
    await page.getByText('暂无符合条件的导入记录').waitFor();
    await page.getByRole('button', { name: '手动上传 md/zip', exact: true }).click();
    const upload = await page.getByRole('dialog', { name: '手动上传反馈 md/zip' }).boundingBox();
    assert(upload.width <= 391);
    await page.goto(`${base}/feedback-results`);
    await page.getByText('暂无回归记录', { exact: true }).waitFor();
    await page.goto(`${base}/feedback-cases`);
    await page.getByRole('heading', { name: '反馈用例库', exact: true }).waitFor();
    await page.goto(`${base}/feedback-regression`);
    await page.getByRole('button', { name: '新建回归集', exact: true }).click();
    const setDialog = page.getByRole('dialog', { name: '新建回归集', exact: true });
    await setDialog.getByPlaceholder('如 公测反馈回归').fill('本地回归集');
    await setDialog.getByRole('button', { name: '保存', exact: true }).click();
    await setDialog.waitFor({ state: 'hidden' });
    assert.equal(writes.find(w => w.path.endsWith('/feedback/sets')).body.name, '本地回归集');
    await page.goto(`${base}/perf-dispatch`);
    await page.getByRole('button', { name: '下发性能任务', exact: true }).click();
    const perf = page.getByRole('dialog', { name: '下发性能任务', exact: true });
    await perf.getByPlaceholder('如 2.4.0 / 竞品豆包').fill('测试版本');
    await perf.getByPlaceholder('40s / 30m / 12h').fill('40');
    await page.waitForTimeout(350);
    await page.screenshot({ path: '/tmp/perf-dispatch-mobile.png' });
    await perf.getByRole('button', { name: '确认下发', exact: true }).click();
    await perf.waitFor({ state: 'hidden' });
    assert.deepEqual(writes.find(w => w.path.endsWith('/perf/jobs')).body, { scenario: '长监控', variant: '测试版本', runner: 'win-01', duration: '40s' });
    await page.goto(`${base}/perf-report`);
    await page.getByRole('heading', { name: '性能报告', exact: true }).waitFor();
    await page.getByText('暂无性能数据，先在「任务下发」建报告集并采集', { exact: true }).waitFor();
    await page.goto(`${base}/perf-collect/1`);
    await page.getByText('启动测试应用', { exact: true }).waitFor();
    await page.getByRole('button', { name: '继续' }).click();
    assert(writes.some(w => w.path.endsWith('/perf/runs/1/signal')));
    assert.deepEqual(errors, []);
    console.log('PASS functional pages: filters, create payload, sticky toolbar/selection, mobile filter toggle');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
